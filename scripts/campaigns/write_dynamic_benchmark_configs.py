"""Write the dynamic benchmark configurations of the model plan (section 12).

Run from the repository root:
    PYTHONPATH=. python scripts/campaigns/write_dynamic_benchmark_configs.py

Each base (Texas same-day, Texas drayage from Houston, Pacific Northwest
drayage from Seattle/Tacoma) gets a ``_hos_us`` variant and three
``_public_u{040,065,090}`` variants at Kullman et al.'s (2021) demand levels.
Variants differ from their base only in the stated block. The regime grid is
frozen before any training.
"""

from __future__ import annotations

import copy
from pathlib import Path

import yaml

from EVRoutingEnv.utils.utils import load_config


ROOT = Path(__file__).resolve().parents[2]
CONFIGS = ROOT / "EVRoutingEnv" / "config_files"

HOUSTON = [{"name": "Port of Houston, Barbours Cut", "lat": 29.6847, "lon": -95.0051}]
PUGET_SOUND = [
    {"name": "Port of Seattle, Terminal 18", "lat": 47.5780, "lon": -122.3530},
    {"name": "Port of Tacoma, Husky Terminal", "lat": 47.2730, "lon": -122.4100},
]

REQUESTS = {
    "arrival_process": "euro_neurips_epochs",
    "epoch_hours": 1.0,
    "dispatch_margin_hours": 1.0,
    "max_requests_per_epoch": 4,
    "initial_requests": 0,
    "max_requests": 200,
    "static_context_size": 200,
    "time_windows": {"enabled": True, "earliest_min": 2.0, "earliest_max": 20.0,
                     "window_width_min": 8.0, "window_width_max": 16.0},
    "deadline_type": "hard",
    "allow_preemptive_returns": False,
    "loading_service_hours": 0.2,
    "lost_request_penalty_hours": 24.0,
    "wait_hours": 0.5,
}

# Drayage is regional: depot and customers within 4 nominal hours of a
# terminal (about 40 network nodes around Houston, 76 around Puget Sound).
DRAYAGE_RADIUS_HOURS = 4.0

BASES = {
    "config_dynamic_texas_sameday": ("config_joint_texas.yaml", "same_day", None, 200),
    "config_dynamic_texas_drayage": ("config_joint_texas.yaml", "drayage", HOUSTON, 36),
    "config_dynamic_pnw_drayage": ("config_joint_pacific_northwest.yaml", "drayage", PUGET_SOUND, 60),
}


def base_config(source: str, mode: str, terminals, context: int) -> dict:
    config = copy.deepcopy(load_config(str(CONFIGS / source)))
    config["environment"].update(num_trucks=10, num_stops=REQUESTS["max_requests"], max_time=36.0)
    config["requests"] = {"mode": mode, **copy.deepcopy(REQUESTS), "static_context_size": context}
    config["depot_charging"] = {"enabled": True, "ports": None, "power_kw": 150.0}
    if terminals is not None:
        config["drayage"] = {
            "terminals": terminals,
            "import_share": 0.5,
            "origin_service_hours": 2.0 / 60.0,
            "destination_service_hours": 4.0 / 60.0,
            "delay_penalty_per_hour": None,
            "energy_model": "network",
            "service_radius_hours": DRAYAGE_RADIUS_HOURS,
        }
    return config


def variants(config: dict):
    yield "", config
    hos = copy.deepcopy(config)
    hos["hours_of_service"] = {"enabled": True, "regime": "us_fmcsa_property", "rest_locations": "anywhere"}
    yield "_hos_us", hos
    for utilization, suffix in ((0.40, "040"), (0.65, "065"), (0.90, "090")):
        public = copy.deepcopy(config)
        public["public_charging"] = {
            "enabled": True,
            "queue_model": "dynamic_mmc",
            "queue_policy": "kullman2021",
            "information": "on_arrival",
            "memory": "shared",
            "exogenous_traffic": {"utilization": utilization, "service_preset": "keskin_truck"},
        }
        yield f"_public_u{suffix}", public


def main() -> None:
    for name, (source, mode, terminals, context) in BASES.items():
        for suffix, config in variants(base_config(source, mode, terminals, context)):
            path = CONFIGS / f"{name}{suffix}.yaml"
            header = (
                f"# Generated by scripts/campaigns/write_dynamic_benchmark_configs.py from {source}.\n"
                "# Edit the script, not this file. See docs/campaigns/"
                "dynamic_stochastic_etruck_model_plan.md, section 12.\n\n"
            )
            path.write_text(header + yaml.safe_dump(config, sort_keys=False))
            print(path.relative_to(ROOT))


if __name__ == "__main__":
    main()
