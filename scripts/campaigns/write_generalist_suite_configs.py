"""Write the five-scenario suite for evaluating one trained policy on every component.

Run from the repository root:
    PYTHONPATH=. python scripts/campaigns/write_generalist_suite_configs.py

Two California, two Texas and one Pacific Northwest scenario. Each adds one
mechanism, so a single policy trained on all five must handle every action kind:

* ``ca_sameday``            -- same-day freight: EURO epochs, hard deadlines, depot manifests;
* ``ca_drayage_combined``   -- Long Beach / Los Angeles drayage with US hours of service and
                               public stations at u = 0.65 (all three components);
* ``tx_longhaul``           -- static long haul where every route must charge;
* ``tx_longhaul_congested`` -- the same instances with public stations at u = 0.65 and port
                               outages (paired seeds isolate the cost of congestion);
* ``pnw_longhaul_hos``      -- long haul under US hours of service with rests only at stops.

Outside demand is lambda = u * c * mu over all ports, so with outages (73.3 % of
ports up) the load on working ports is u / 0.733: u = 0.65 gives 0.89, heavily
congested but stable, while u = 0.90 would give 1.23 and queues that grow
without bound. Request blocks follow ``write_dynamic_benchmark_configs.py``.
Long-haul horizons are 72 h because 48 h binds under congestion and hours of
service (which allow 96 h). Every scenario uses ``nominal_eta``: the
dispatcher sees telematics ETAs, not realized arrivals.
"""

from __future__ import annotations

import copy

import yaml

from EVRoutingEnv.utils.utils import load_config
from scripts.campaigns.write_dynamic_benchmark_configs import CONFIGS, base_config


SUITE = CONFIGS / "generalist_suite"

# Gate C proposals; both resolve to network nodes within 5 km.
LONG_BEACH_LOS_ANGELES = [
    {"name": "Port of Long Beach, Pier T", "lat": 33.7550, "lon": -118.2370},
    {"name": "Port of Los Angeles, TraPac", "lat": 33.7660, "lon": -118.2700},
]
LONGHAUL_HOURS = 72.0
OBSERVATION = {"in_flight_information": "nominal_eta"}
US_HOURS = {"enabled": True, "regime": "us_fmcsa_property", "rest_locations": "anywhere"}


def public(utilization: float, *, outages: bool = False) -> dict:
    block = {
        "enabled": True,
        "queue_model": "dynamic_mmc",
        "queue_policy": "kullman2021",
        "information": "on_arrival",
        "memory": "shared",
        "exogenous_traffic": {"utilization": utilization, "service_preset": "keskin_truck"},
    }
    if outages:
        block["outages"] = {"enabled": True, "port_availability": 0.733, "mean_repair_hours": 24.0}
    return block


def _longhaul(source: str) -> dict:
    config = copy.deepcopy(load_config(str(CONFIGS / source)))
    config["environment"]["max_time"] = LONGHAUL_HOURS
    return config


def suite() -> dict[str, dict]:
    ca_sameday = base_config("config_joint_california_10t30c.yaml", "same_day", None, 200)

    ca_drayage = base_config("config_joint_california_10t30c.yaml", "drayage", LONG_BEACH_LOS_ANGELES, 36)
    ca_drayage["hours_of_service"] = copy.deepcopy(US_HOURS)
    ca_drayage["public_charging"] = public(0.65)

    tx_longhaul = _longhaul("config_joint_texas_longhaul.yaml")
    tx_congested = _longhaul("config_joint_texas_longhaul.yaml")
    tx_congested["public_charging"] = public(0.65, outages=True)

    pnw_hos = _longhaul("config_joint_pacific_northwest_longhaul.yaml")
    pnw_hos["hours_of_service"] = {**US_HOURS, "rest_locations": "stops_only"}

    configs = {
        "ca_sameday": ca_sameday,
        "ca_drayage_combined": ca_drayage,
        "tx_longhaul": tx_longhaul,
        "tx_longhaul_congested": tx_congested,
        "pnw_longhaul_hos": pnw_hos,
    }
    for config in configs.values():
        config["observation"] = dict(OBSERVATION)
    return configs


def main() -> None:
    SUITE.mkdir(exist_ok=True)
    for name, config in suite().items():
        path = SUITE / f"{name}.yaml"
        header = (
            "# Generated by scripts/campaigns/write_generalist_suite_configs.py.\n"
            "# Edit the script, not this file.\n\n"
        )
        path.write_text(header + yaml.safe_dump(config, sort_keys=False))
        print(path.relative_to(CONFIGS.parents[1]))


if __name__ == "__main__":
    main()
